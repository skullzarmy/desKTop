import Foundation
import desKTopCore

public struct UnifiedTokenTests {
    public static func run() throws {
        // SVG
        let svgToken = UnifiedToken(
            contract: "KT1test",
            tokenId: "1",
            name: "SVG Art",
            mimeType: "image/svg+xml"
        )
        try assertEqual(svgToken.mediaCategory, .vectorImage)

        // GIF
        let gifToken = UnifiedToken(
            contract: "KT1test",
            tokenId: "2",
            name: "Animated GIF",
            mimeType: "image/gif"
        )
        try assertEqual(gifToken.mediaCategory, .animatedImage)

        // Video MP4
        let videoToken = UnifiedToken(
            contract: "KT1test",
            tokenId: "3",
            name: "MP4 Loop",
            mimeType: "video/mp4"
        )
        try assertEqual(videoToken.mediaCategory, .video)

        // Aleatory
        let aleaToken = UnifiedToken(
            contract: "KT1test",
            tokenId: "4",
            name: "Aleatory Piece",
            aleatory: AleatoryMetadata(code: "console.log('alea')")
        )
        try assertEqual(aleaToken.mediaCategory, .aleatory)

        // Bootloader
        let btldrToken = UnifiedToken(
            contract: "KT1test",
            tokenId: "5",
            name: "BTLDR On-Chain Piece",
            description: "Generated by BTLDR engine v1"
        )
        try assertEqual(btldrToken.mediaCategory, .bootloader)

        // Audio/3D
        let modelToken = UnifiedToken(
            contract: "KT1test",
            tokenId: "6",
            name: "3D Sculpture",
            mimeType: "model/gltf-binary",
            artifactUri: "ipfs://model.glb",
            displayUri: "ipfs://poster.png"
        )
        try assertEqual(modelToken.mediaCategory, .audio3d)
        try assertEqual(modelToken.primaryWallpaperUri, "ipfs://poster.png")

        // fxhash GENTK
        let fxhashGentk = UnifiedToken(
            contract: "KT1KEa8z6vWXDJrVqtMrAeDVzsvxat3kHaCE",
            tokenId: "402352",
            name: "Token of Babel #4",
            artifactUri: "ipfs://QmYQZCcJtY9GjPEn85rtycyd7ATAQyTVjVvhezgmFcvYBB?fxhash=oogXdxkNnryRNZfN3zvhPE6GzqkGhGoyio2shfTcnRQb5bha4gP",
            rawMetadata: ["symbol": "GENTK", "iterationHash": "oogXdxkNnryRNZfN3zvhPE6GzqkGhGoyio2shfTcnRQb5bha4gP"]
        )
        try assertEqual(fxhashGentk.mediaCategory, .fxhash)

        // IPFS Gateway Public URL Resolution
        let resolvedURL = IPFSGatewayManager.resolvePublicURL(for: "ipfs://QmQyNNfhfnFSW3geXMRau7JrKq38FuCi3Ds12axxEnREdf")
        try assertEqual(resolvedURL?.absoluteString, "https://ipfs.fileship.xyz/QmQyNNfhfnFSW3geXMRau7JrKq38FuCi3Ds12axxEnREdf")

        // Composite ID
        let token = UnifiedToken(
            contract: "KT1RJ6PbjHpwc3M5rw5s2Nbmefwbuwbdxton",
            tokenId: "789",
            name: "Sample"
        )
        try assertEqual(token.id, "KT1RJ6PbjHpwc3M5rw5s2Nbmefwbuwbdxton_789")

        // Hermandad de los Fracasados (formats has display.webp first, but artifact.gif in formats)
        let hermandadToken = UnifiedToken(
            contract: "KT1VHoxXoYX9LYEKe1AjPHaRq3zPZ4cZd6my",
            tokenId: "10632",
            name: "Hermandad de los Fracasados",
            artifactUri: "ipfs://bafybeietwsvimdp6fzkm4zks77rmx24trxbfbjb3af4szn4d4voy2ncmtq",
            displayUri: "ipfs://bafybeia6pazj37yodz7w74e6lm6gj2mklrarsuv2wcnwrarlkhfvdctuje",
            thumbnailUri: "ipfs://bafybeie7tx7ru6wjv6sshdyiru3ebsolsp3svj27tcxc7jhnos3x4u3k24",
            formats: [
                TokenFormat(uri: "ipfs://bafybeia6pazj37yodz7w74e6lm6gj2mklrarsuv2wcnwrarlkhfvdctuje", mimeType: "image/webp"),
                TokenFormat(uri: "ipfs://bafybeie7tx7ru6wjv6sshdyiru3ebsolsp3svj27tcxc7jhnos3x4u3k24", mimeType: "image/webp"),
                TokenFormat(uri: "ipfs://bafybeietwsvimdp6fzkm4zks77rmx24trxbfbjb3af4szn4d4voy2ncmtq", mimeType: "image/gif")
            ],
            rawMetadata: ["tags": "skull,darkart,gif,glitch"]
        )
        try assertEqual(hermandadToken.mediaCategory, .animatedImage)
        try assertEqual(hermandadToken.mediaCategory.displayName, "GIF")

        // Non-visual metadata rejection (avoid loading json or markdown as wallpaper)
        let textArticleToken = UnifiedToken(
            contract: "KT1test",
            tokenId: "99",
            name: "Guide to AI",
            artifactUri: "ipfs://QmArticle/metadata.json",
            displayUri: "ipfs://QmCoverArt.jpg",
            thumbnailUri: "ipfs://QmThumb.jpg"
        )
        try assertEqual(textArticleToken.primaryWallpaperUri, "ipfs://QmCoverArt.jpg")
        try assertEqual(textArticleToken.preferredThumbnailUri, "ipfs://QmThumb.jpg")

        // Marketplace detection: Teia (hic et nunc contract)
        let teiaToken = UnifiedToken(
            contract: "KT1RJ6PbjHpwc3M5rw5s2Nbmefwbuwbdxton",
            tokenId: "168685",
            name: "Teia Piece"
        )
        try assertEqual(teiaToken.marketplace, .teia)
        try assertEqual(teiaToken.marketplaceTokenURL?.absoluteString, "https://teia.art/objkt/168685")

        // Marketplace detection: Aleatory
        let aleatoryToken = UnifiedToken(
            contract: "KT1AleatoryContract",
            tokenId: "42",
            name: "Aleatory Piece",
            aleatory: AleatoryMetadata(code: "function draw(){}", seed: "oo123", params: nil, provider: nil, encoding: "raw", version: 1)
        )
        try assertEqual(aleatoryToken.marketplace, .aleatory)
        try assertEqual(aleatoryToken.marketplaceTokenURL?.absoluteString, "https://aleatory.art")

        // Marketplace detection: fxhash
        let fxhashToken = UnifiedToken(
            contract: "KT1KEa8z6vWXDJrVqtMrAeDVzsvxat3kHaCE",
            tokenId: "1001",
            name: "fxhash Gentk"
        )
        try assertEqual(fxhashToken.marketplace, .fxhash)
        try assertEqual(fxhashToken.marketplaceTokenURL?.absoluteString, "https://www.fxhash.xyz/gentk/1001")

        // Marketplace detection: objkt.com fallback
        let objktToken = UnifiedToken(
            contract: "KT1CustomObjktContract",
            tokenId: "7",
            name: "Objkt Piece"
        )
        try assertEqual(objktToken.marketplace, .objkt)
        try assertEqual(objktToken.marketplaceTokenURL?.absoluteString, "https://objkt.com/tokens/KT1CustomObjktContract/7")

        // Objkt safety flags (accessibility.hazards + __hazards_, content_rating + __nsfw_, flag)
        let flashingToken = UnifiedToken(
            contract: "KT1Flash",
            tokenId: "1",
            name: "Strobe",
            accessibilityHazards: ["flashing"]
        )
        try assertTrue(flashingToken.hasFlashingHazard)
        try assertTrue(flashingToken.isHiddenByContentFilters(hideFlashing: true, hideAdult: false, hideFlagged: false))
        try assertFalse(flashingToken.isHiddenByContentFilters(hideFlashing: false, hideAdult: true, hideFlagged: true))

        let legacyHazardAttrToken = UnifiedToken(
            contract: "KT1FlashLegacy",
            tokenId: "2",
            name: "Legacy Strobe",
            attributes: [TokenAttribute(name: "__hazards_", value: "flashing")]
        )
        try assertTrue(legacyHazardAttrToken.hasFlashingHazard)

        let matureToken = UnifiedToken(
            contract: "KT1Adult",
            tokenId: "3",
            name: "Mature",
            contentRating: "mature"
        )
        try assertTrue(matureToken.isAdultContent)
        try assertTrue(matureToken.isHiddenByContentFilters(hideFlashing: false, hideAdult: true, hideFlagged: false))

        let legacyNsfwAttrToken = UnifiedToken(
            contract: "KT1AdultLegacy",
            tokenId: "4",
            name: "Legacy NSFW",
            attributes: [TokenAttribute(name: "__nsfw_", value: "true")]
        )
        try assertTrue(legacyNsfwAttrToken.isAdultContent)

        let flaggedToken = UnifiedToken(
            contract: "KT1Flagged",
            tokenId: "5",
            name: "Flagged",
            moderationFlag: "flagged"
        )
        try assertTrue(flaggedToken.isModerationFlagged)
        try assertTrue(flaggedToken.isHiddenByContentFilters(hideFlashing: false, hideAdult: false, hideFlagged: true))

        // Filter-level Smart Gallery exclusion
        let safeCriteria = GalleryFilterCriteria(excludeFlashingHazards: true, excludeAdultContent: true)
        try assertFalse(safeCriteria.matches(token: flashingToken))
        try assertFalse(safeCriteria.matches(token: legacyNsfwAttrToken))
        try assertTrue(safeCriteria.matches(token: objktToken))
    }
}
